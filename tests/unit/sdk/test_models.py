"""Unit tests: Span / SpanBatch model validation & serialization."""

from __future__ import annotations

from datetime import datetime, timezone

import pytest
from pydantic import ValidationError

from nexus_agent.models import (
    Alert,
    FailureType,
    PatchProposal,
    PatchType,
    Span,
    SpanBatch,
    SpanType,
)


def _span(**overrides) -> Span:
    base = dict(
        trace_id="trace_abc",
        agent_name="agent",
        span_type=SpanType.LLM_CALL,
        input="hello",
        duration_ms=1.2,
        client_timestamp=datetime.now(timezone.utc),
        sdk_version="1.0.0",
    )
    base.update(overrides)
    return Span(**base)


def test_span_id_autogenerated_with_prefix():
    span = _span()
    assert span.span_id.startswith("span_")
    assert len(span.span_id) > len("span_")


def test_span_requires_trace_id():
    with pytest.raises(ValidationError):
        Span(  # type: ignore[call-arg]
            agent_name="a",
            span_type=SpanType.LLM_CALL,
            input="x",
            duration_ms=1.0,
            client_timestamp=datetime.now(timezone.utc),
            sdk_version="1.0.0",
        )


def test_span_serialization_round_trip():
    span = _span(output="world", metadata={"model": "gemini"})
    dumped = span.model_dump(mode="json")
    restored = Span.model_validate(dumped)
    assert restored.output == "world"
    assert restored.metadata["model"] == "gemini"
    assert restored.span_type == SpanType.LLM_CALL


def test_span_batch_max_length_enforced():
    spans = [_span() for _ in range(101)]
    with pytest.raises(ValidationError):
        SpanBatch(spans=spans)


def test_span_batch_batch_id_autogenerated():
    batch = SpanBatch(spans=[_span()])
    assert batch.batch_id
    assert len(batch.spans) == 1


def test_span_type_enum_values():
    assert SpanType.TOOL_CALL.value == "tool_call"
    assert SpanType.AGENT_HANDOFF.value == "agent_handoff"


def test_failure_and_patch_enums():
    assert FailureType.TOOL_MISFIRE.value == "TOOL_MISFIRE"
    assert PatchType.PROMPT_PATCH.value == "PROMPT_PATCH"
    assert set(PatchType.__members__) >= {
        "PROMPT_PATCH",
        "TOOL_CONFIG_PATCH",
        "MEMORY_PATCH",
        "RETRY_POLICY_PATCH",
    }


def test_patch_proposal_defaults():
    p = PatchProposal(
        alert_id="a1",
        trace_id="t1",
        failure_type=FailureType.TOOL_MISFIRE,
        patch_type=PatchType.TOOL_CONFIG_PATCH,
        target_component="search_tool",
        explanation="Add a non-empty query validation rule before invoking the tool.",
        patch_content="if not query.strip(): raise ValueError('empty query')",
        confidence="HIGH",
        estimated_impact="eval score +0.3",
        root_cause_analysis="empty query passed to search tool",
    )
    assert p.proposal_id.startswith("patch_")
    assert p.status == "PENDING_REVIEW"


def test_alert_defaults():
    a = Alert(trace_id="t1", agent_name="agent", failure_type=FailureType.LOOP_DETECTED)
    assert a.severity.value == "HIGH"
    assert a.status.value == "OPEN"
