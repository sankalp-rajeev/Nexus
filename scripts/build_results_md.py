def rows_from_published_table(text: str) -> list[list[str]]:
    rows = []
    for ln in text.splitlines():
        if ln.startswith("| ") and not ln.startswith("| ID "):
            cells = [c.strip() for c in ln.strip().strip("|").split(" | ")]
            if len(cells) == 7:
                rows.append(cells)
    return rows


