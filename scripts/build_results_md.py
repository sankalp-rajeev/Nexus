# --------------------------------------------------------------------------- io
def _git(*args: str) -> str:
    return subprocess.check_output(
        ["git", "-c", f"safe.directory={REPO.replace(chr(92), '/')}", *args],
        cwd=REPO, text=True, encoding="utf-8")


def load(rel: str) -> dict:
    rel = rel.replace("\\", "/")
    # Only these reviewed external aggregate JSONs are exceptions to the
    # filename guard. NexusBench TEST results and arbitrary external *_test
    # files remain sealed; no raw TRAIL trace or annotation is opened.
    if rel in EXTERNAL_AGGREGATES:
        return load_aggregate(rel, REPO)
    low = rel.lower()
    if rel in SEALED_FILES or "_test" in low or low.startswith("reports/phase4/test/"):
        raise RuntimeError(f"sealed TEST file requested: {rel}")
    with open(os.path.join(REPO, rel), encoding="utf-8") as fh:
        return json.load(fh)


def read_text(rel: str) -> list[str]:
    with open(os.path.join(REPO, rel), encoding="utf-8") as fh:
        return fh.read().splitlines()


def _file_commits() -> dict[str, dict[str, str]]:
    with open(FILE_COMMITS, encoding="utf-8") as fh:
        return json.load(fh)["files"]


_RECORDING: dict[str, dict[str, str]] | None = None


def _pinned(rel: str) -> dict[str, str]:
    if _RECORDING is not None:  # --refresh-pins: read git and remember what the render asked for
        return _RECORDING.setdefault(rel, git_last_commit(rel))
    files = _file_commits()
    if rel not in files:
        raise RuntimeError(f"{rel} is not pinned in {os.path.relpath(FILE_COMMITS, REPO)}; "
                           "run: python scripts/build_results_md.py --refresh-pins")
    return files[rel]


def last_commit(rel: str) -> str:
    return _pinned(rel)["commit"]


def last_date(rel: str) -> str:
    return _pinned(rel)["date"]


def git_last_commit(rel: str) -> dict[str, str]:
    """Last commit touching ``rel`` and its date in the commit's own time zone (machine-independent)."""
    out = _git("log", "-1", "--format=%h %cd", "--date=format:%Y-%m-%d", "--", rel).strip()
    commit, date = out.split(" ")
    return {"commit": commit, "date": date}


def dig(doc: dict, path: str):
    cur = doc
    for part in path.split("/"):
        if part:
            cur = cur[part]
    return cur


# ------------------------------------------------------------------- intervals
def _counts(node: dict) -> tuple[int, int, list | None]:
    k = node["k"] if "k" in node else node["successes"]
    n = node["n"] if "n" in node else node["total"]
    ci = node.get("ci95_clopper_pearson") or node.get("ci95")
    return int(k), int(n), ci


def fmt_ci(label: str, node: dict) -> str:
    k, n, ci = _counts(node)
    if ci is None:
        return f"{label} {k}/{n} (no CI)"
    return f"{label} {k}/{n} ({ci[0]:.2f}-{ci[1]:.2f})"


def fmt_w(label: str, k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{label} {k}/{n} W ({lo:.2f}-{hi:.2f})"


def ci_cell(parts: list[str]) -> str:
    return "<br>".join(parts) if parts else "-"


def _specs(file: str, items: list[tuple[str, str]]) -> list[tuple[str, str, str]]:
    return [(label, file, path) for label, path in items]


def _cls(file: str, root: str, table: list[tuple[str, str, str]]) -> list[tuple[str, str, str]]:
    return [(lab, file, f"{root}/per_class/{cls}/{metric}") for lab, cls, metric in table]


