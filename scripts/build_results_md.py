P2_TEST_REPORT = "reports/phase2/test_report.md"


def phase2_test_ci() -> dict[str, tuple[list[str], str]]:
    """CIs for D1 and D5, read from the committed TEST text report (not a result file)."""
    lines = read_text(P2_TEST_REPORT)
    pat = re.compile(r"(\d\.\d+) \((\d+)/(\d+); ([0-9.]+)\u2013([0-9.]+)\)")

    def cells(prefix: str, start: int) -> tuple[int, list[tuple[int, int, str, str]]]:
        for i in range(start, len(lines)):
            if lines[i].startswith(prefix):
                found = [(int(m.group(2)), int(m.group(3)), m.group(4), m.group(5))
                         for m in pat.finditer(lines[i])]
                return i + 1, found
        raise RuntimeError(f"{P2_TEST_REPORT}: no line starting {prefix!r}")

    section = next(i for i, ln in enumerate(lines) if ln.startswith("## All models"))
    out: list[str] = []
    refs: list[str] = []
    for label, cls, idx in (("H P", "| HALLUCINATION |", 0), ("H R", "| HALLUCINATION |", 1),
                            ("CB R", "| CONTEXT_BLEED |", 1), ("PD R", "| PLAN_DRIFT |", 1)):
        ln, found = cells(cls, section)
        k, n, lo, hi = found[idx]
        out.append(f"{label} {k}/{n} ({lo}-{hi})")
        refs.append(ln)
    d5_head = next(i for i, ln in enumerate(lines) if ln.startswith("## D5"))
    fa_line = next(i for i in range(d5_head, len(lines)) if lines[i].startswith("- detectors"))
    m = re.search(r"\((\d+)/(\d+)\)", lines[fa_line])
    d5 = [fmt_w("FA (NORMAL flagged)", int(m.group(1)), int(m.group(2)))]
    where = f"lines {sorted(set(refs))[0]}-{sorted(set(refs))[-1]}"
    return {"D1": (out, f"{P2_TEST_REPORT} {where} (Clopper-Pearson as printed)"),
            "D5": (d5, f"{P2_TEST_REPORT} line {fa_line + 1} (k/n as printed; Wilson computed)")}


