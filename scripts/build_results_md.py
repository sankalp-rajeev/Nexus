def render() -> str:
    pub = {c[0]: c for c in published_rows()}
    sealed_ci = phase2_test_ci()
    all_rows: list[dict] = []
    out = [HEADER]
    used: set[str] = set()

    def take(ids: list[str]) -> list[dict]:
        rows = []
        for i in ids:
            used.add(i)
            rows.append(existing_row(pub[i], sealed_ci))
        return rows

    sec, cs = [], c_rows()
    for title, ids in SECTIONS:
        rows = take(ids)
        sec.append((title, rows))
    p4, p4doc = phase4_rows()
    p4_existing = take(PHASE4_EXISTING)
    p6 = phase6_rows()
    leftover = [i for i in pub if i not in used]
    if leftover:
        raise RuntimeError(f"published rows not placed in a section: {leftover}")

    for title, rows in sec:
        out.append(f"## {title}\n\n" + table(rows) + "\n")
        all_rows += rows
    out.append("## Phase 3: critic (DEV, oracle evidence)\n\n" + table(cs) + "\n")
    out.append("## Phase 4: healing\n\nHeadline finding first (TEST, scored once), then the DEV "
               "development rows and the per-arm TEST rows.\n\n" + table(p4 + p4_existing)
               + reconciliation_text(p4doc))
    all_rows += cs + p4 + p4_existing
    out.append(phase5_section())
    out.append("\n## Phase 6: stack, live detectors and OTel\n\n" + table(p6))
    all_rows += p6
    out.append(external_trail_section())
    out.append(limitations(all_rows))
    return "".join(out)


def _write_json(path: str, doc: dict) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")


def refresh_pins() -> None:
    global _RECORDING
    if _git("rev-parse", "--is-shallow-repository").strip() == "true":
        raise SystemExit("--refresh-pins needs full history: git fetch --unshallow --tags")
    if _git("rev-parse", f"{TAG}^{{commit}}").strip() != TAG_COMMIT:
        raise SystemExit(f"tag {TAG} does not point at {TAG_COMMIT}")
    sealed = {
        "provenance": {
            "tag": TAG, "tag_commit": TAG_COMMIT, "source_file": "RESULTS.md",
            "statement": "text only, TEST data not opened: the published table rows of RESULTS.md at "
                         f"tag {TAG}, copied by scripts/build_results_md.py --refresh-pins",
        },
        "rows": git_published_rows(),
    }
    _write_json(SEALED_ROWS, sealed)
    # Render once while reading git, recording exactly the files whose commit the table prints.
    _RECORDING = {}
    try:
        render()
        recorded = dict(sorted(_RECORDING.items()))
    finally:
        _RECORDING = None
    _write_json(FILE_COMMITS, {
        "provenance": {
            "statement": "last commit touching each file (git log -1) and that commit's date in its own "
                         "recorded time zone; written by scripts/build_results_md.py --refresh-pins",
        },
        "files": recorded,
    })
    print(f"wrote {SEALED_ROWS} and {FILE_COMMITS}")


def normalise(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def main() -> int:
    if "--refresh-pins" in sys.argv:
        refresh_pins()
    text = render()
    if "--check" in sys.argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8", newline="") as fh:
                current = fh.read()
        if normalise(current) != normalise(text):
            print("RESULTS.md is stale; run: python scripts/build_results_md.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
