"""Regenerate RESULTS.md from results/*.json. Never hand-edit RESULTS.md.

    python scripts/build_results_md.py          # write
    python scripts/build_results_md.py --check  # exit 1 if RESULTS.md is stale
"""

from __future__ import annotations

import glob
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(REPO, "RESULTS.md")

HEADER = """# Nexus Results

Single source of truth for every number Nexus claims. Each row links to a
committed JSON file in `results/` that records the provider, model, mock flag,
seed, date and git commit. This file is generated by
`python scripts/build_results_md.py`; do not edit it by hand.

Rows marked **mock** come from deterministic test doubles and are not evidence
of real-model behaviour.

| ID | Result | Provider / model | Mock | Date | Commit | File |
|---|---|---|---|---|---|---|
"""


def render() -> str:
    rows = []
    for path in sorted(glob.glob(os.path.join(REPO, "results", "*.json"))):
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        if "experiment_id" not in doc:
            continue  # auxiliary files (e.g. cost ledgers) are not result rows
        prov = doc.get("provenance", {})
        rel = os.path.relpath(path, REPO).replace(os.sep, "/")
        mock = "**mock**" if prov.get("mock") else "no"
        commit = prov.get("git_commit", "?") + ("+dirty" if prov.get("git_dirty") else "")
        rows.append(
            f"| {doc['experiment_id']} | {doc.get('summary', '')} | "
            f"{prov.get('provider', '?')} / {prov.get('model', '?')} | {mock} | "
            f"{str(prov.get('date_utc', '?'))[:10]} | `{commit}` | [{rel}]({rel}) |"
        )
    if not rows:
        rows.append("| — | No results yet | | | | | |")
    return HEADER + "\n".join(rows) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != text:
            print("RESULTS.md is stale; run: python scripts/build_results_md.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
